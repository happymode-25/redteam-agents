"""Ticket export for Jira / Linear (Phase 4), with stable dedup keys.

Every ticket carries the finding fingerprint as a `dedup:<key>` label so a
scheduled re-run can be deduplicated by the ticketing system instead of
creating a second ticket for the same issue. The description is redacted
through the same process-wide redactor as reports — a ticket is an external
artifact and must not carry our identity secrets.

Input is the findings JSON written by every run (artifacts/findings-*.json).
"""

from __future__ import annotations

import argparse
import csv
import io
import json
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable

from .drift import fingerprint
from .redact import redactor
from .state import Finding

JIRA_PRIORITY = {"critical": "Highest", "high": "High", "medium": "Medium",
                 "low": "Low", "info": "Lowest"}
LINEAR_PRIORITY = {"critical": "Urgent", "high": "High", "medium": "Medium",
                   "low": "Low", "info": "No priority"}


def load_findings(path: str | Path) -> list[Finding]:
    """Read a findings JSON written by SharedState.save (or a bare list)."""
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    items = data.get("findings", []) if isinstance(data, dict) else data
    fields = set(Finding.__dataclass_fields__)
    findings: list[Finding] = []
    for item in items:
        if isinstance(item, dict):
            findings.append(Finding(**{k: v for k, v in item.items()
                                       if k in fields}))
    return findings


@dataclass
class Ticket:
    dedup_key: str
    summary: str
    description: str
    priority: str
    issue_type: str
    labels: str


def to_ticket(f: Finding, priority_map: dict[str, str] | None = None) -> Ticket:
    priority_map = priority_map or JIRA_PRIORITY
    key = fingerprint(f)
    classification = ", ".join(part for part in (
        f"CWE {f.cwe}" if f.cwe else "",
        f"CVSS {f.cvss}" if f.cvss else "",
        f"CVE {f.cves}" if f.cves else "",
    ) if part)
    description = redactor.scrub("\n".join(part for part in (
        f"Target: {f.target}",
        f"Severity: {f.severity}",
        f"Status: {f.status}",
        f"Discovered by: {f.tool}" if f.tool else "",
        f"Classification: {classification}" if classification else "",
        "",
        "Evidence:",
        (f.evidence or "(no evidence recorded)"),
        "",
        f"Remediation: {f.remediation}" if f.remediation else "",
        "",
        f"Dedup key: {key}",
        "Generated by redteam-agents — verify every finding manually before "
        "acting on it; autonomous assessments can be wrong.",
    ) if part is not None))
    return Ticket(
        dedup_key=key,
        summary=redactor.scrub(
            f"[{f.severity.upper()}] {f.title}" + (f" ({f.target})" if f.target else "")),
        description=description,
        priority=priority_map.get(f.severity, "Medium"),
        issue_type="Bug",
        labels=",".join(label for label in (
            "security", f"severity:{f.severity}", f"dedup:{key}",
            *([f"cwe:{f.cwe}"] if f.cwe else []),
        )),
    )


def to_tickets(findings: Iterable[Finding], kind: str = "jira") -> list[Ticket]:
    pmap = LINEAR_PRIORITY if kind == "linear" else JIRA_PRIORITY
    return [to_ticket(f, pmap) for f in findings]


def _csv(rows: list[dict], columns: list[str]) -> str:
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=columns, extrasaction="ignore")
    writer.writeheader()
    for row in rows:
        writer.writerow(row)
    return buf.getvalue()


def render(tickets: list[Ticket], kind: str) -> str:
    if kind == "jira":
        return _csv([{"Summary": t.summary, "Issue Type": t.issue_type,
                      "Priority": t.priority, "Labels": t.labels,
                      "Description": t.description} for t in tickets],
                    ["Summary", "Issue Type", "Priority", "Labels", "Description"])
    if kind == "linear":
        return _csv([{"Title": t.summary, "Description": t.description,
                      "Priority": t.priority, "Labels": t.labels}
                     for t in tickets],
                    ["Title", "Description", "Priority", "Labels"])
    if kind == "markdown":
        lines = ["# Security tickets", ""]
        for t in tickets:
            lines += [f"## {t.summary}", "",
                      f"- **Priority:** {t.priority}",
                      f"- **Dedup key:** `{t.dedup_key}`",
                      f"- **Labels:** {t.labels}", "",
                      "```", t.description, "```", ""]
        return "\n".join(lines)
    raise ValueError(f"unknown ticket format {kind!r} (jira|linear|markdown)")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Export findings to Jira/Linear tickets (or markdown)")
    parser.add_argument("--findings", required=True,
                        help="findings JSON written by a run")
    parser.add_argument("--format", default="jira",
                        choices=["jira", "linear", "markdown"])
    parser.add_argument("--out", default="", help="output path (default: stdout)")
    args = parser.parse_args(argv)

    findings = load_findings(args.findings)
    if not findings:
        print("no findings in that file — nothing to export", file=sys.stderr)
        return 1
    tickets = to_tickets(findings, kind=args.format)
    text = render(tickets, args.format)
    if args.out:
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")
        print(f"wrote {len(tickets)} ticket(s) to {out}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
